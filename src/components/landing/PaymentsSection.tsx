import {
  Banknote,
  HandCoins,
  ArrowLeftRight,
  MessageCircle,
  Smartphone,
  CheckCheck,
  type LucideIcon,
} from "lucide-react";
import { RevealCssClass } from "@/hooks/useReveal";
import {
  PAYMENT_TYPES,
  PAYMENT_TYPE_AR,
  PAYMENT_TYPE_DESCRIPTIONS,
  type PaymentType,
} from "@/lib/constants";
import { WALLET_CAP_LYD, libyanaUssdCode } from "@/lib/payment-constants";

/* r142 «الخط» — PaymentsSection «محطات الدفع» (chapter 04):
 * the REAL local payment methods (lib/constants PAYMENT_TYPES) as road
 * toll-station plates — the money leg of the line, styled as lane
 * markings. Nothing invented:
 * · the six methods + their descriptions are verbatim from constants;
 * · the USSD sample is GENERATED by the real libyanaUssdCode() —
 *   the same generator the checkout shows customers;
 * · the wallet cap is the real WALLET_CAP_LYD (99 د.ل per transfer);
 * · amounts ride the د.ل seam (lib/money) vocabulary.
 * Server component: zero JS. */

const METHOD_ICON: Record<PaymentType, LucideIcon> = {
  CASH: Banknote,
  COD: HandCoins,
  MANUAL: ArrowLeftRight,
  WHATSAPP: MessageCircle,
  MADAR: Smartphone,
  LIBYANA: Smartphone,
};

/** The real USSD generator, fed an illustrative target — the exact
 * pattern a customer sees at checkout (millimes-encoded amount). */
const USSD_SAMPLE = libyanaUssdCode("0910000000", 45);

export function PaymentsSection() {
  return (
    <section id="payments" className="ln-chapter ln-pay">
      <div className="ln-chapter-head">
        <span className="ln-route-stop" data-route-stop aria-hidden="true" />
        <span className="ln-label">{'04 — محطات الدفع'}</span>
        <RevealCssClass as="h2" className="ln-chapter-title" delay={1}>
          المال يعبر <em>بطرق ليبيا</em>
        </RevealCssClass>
        <RevealCssClass as="p" className="ln-chapter-lede" delay={2}>
          ست طرق دفع حقيقية تُدار من لوحة التاجر وتظهر في صفحة الطلب —
          من النقد عند الباب إلى رموز التحويل السريع، والعملة دينار
          ليبي بدقّة الدرهم.
        </RevealCssClass>
      </div>

      <RevealCssClass as="div" delay={2}>
        <ul className="ln-pay-lane">
          {PAYMENT_TYPES.map((method, i) => {
            const Icon = METHOD_ICON[method];
            return (
              <li key={method} className="ln-pay-station" data-method={method}>
                <span className="ln-pay-index ln-mono" aria-hidden="true">
                  {String(i + 1).padStart(2, "0")}
                </span>
                <span className="ln-pay-ico" aria-hidden="true">
                  <Icon size={20} strokeWidth={2} />
                </span>
                <div className="ln-pay-body">
                  <strong className="ln-pay-name">{PAYMENT_TYPE_AR[method]}</strong>
                  <span className="ln-pay-desc">{PAYMENT_TYPE_DESCRIPTIONS[method]}</span>
                </div>
                <span className="ln-pay-key ln-mono" dir="ltr" aria-hidden="true">
                  {method}
                </span>
              </li>
            );
          })}
        </ul>
      </RevealCssClass>

      <RevealCssClass as="div" delay={3}>
        <div className="ln-pay-facts">
          <div className="ln-pay-fact">
            <CheckCheck size={16} aria-hidden="true" />
            <div>
              <strong>رمز التحويل السريع (USSD) يُولَّد تلقائياً</strong>
              <p>
                عند اختيار محفظة موبايل، يرى العميل رمز الاتصال جاهزاً
                بالمبلغ — ينسخه ويتصل. النمط (نموذج لـ 45 د.ل):
              </p>
              <code className="ln-mono" dir="ltr">{USSD_SAMPLE}</code>
            </div>
          </div>
          <div className="ln-pay-fact">
            <Smartphone size={16} aria-hidden="true" />
            <div>
              <strong>سقف التحويل الواحد {WALLET_CAP_LYD} د.ل</strong>
              <p>
                قيد شبكات المحافظ الليبية نفسها — والمنصّة تتحقق منه
                قبل إتمام الطلب.
              </p>
            </div>
          </div>
          <div className="ln-pay-fact">
            <Banknote size={16} aria-hidden="true" />
            <div>
              <strong>الدفع عند التوصيل محطة في الرحلة</strong>
              <p>
                المندوب يحصّل نقداً عند الباب، والتاجر يؤكد الاستلام من
                اللوحة — الحالة تنتقل من «غير مدفوع» إلى «مدفوع».
              </p>
            </div>
          </div>
        </div>
      </RevealCssClass>
    </section>
  );
}
